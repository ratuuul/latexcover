  // normalized string + map back to original indices (dots are skipped in matching)
  function normIdx(s){
    const str = [], idx = [], lower = String(s || '').toLowerCase();
    for(let i = 0; i < lower.length; i++){
      if(lower[i] === '.') continue;
      str.push(lower[i]); idx.push(i);
    }
    return { str: str.join(''), idx };
  }
  // wrap query-matched chars of target in <mark> (contiguous preferred, else subsequence)
  function highlight(target, q){
    target = String(target ?? '');
    const t = normIdx(target), qq = normIdx(q).str.trim();
    if(!qq) return escHtml(target);
    let hits = null;
    const pos = t.str.indexOf(qq);
    if(pos !== -1){
      hits = new Set();
      for(let i = pos; i < pos + qq.length; i++) hits.add(t.idx[i]);
    } else {
      hits = new Set();
      let qi = 0;
      for(let i = 0; i < t.str.length && qi < qq.length; i++){
        if(t.str[i] === qq[qi]){ hits.add(t.idx[i]); qi++; }
      }
      if(qi !== qq.length) return escHtml(target);
    }
    let out = '';
    for(let i = 0; i < target.length; i++){
      out += hits.has(i) ? '<mark>' + escHtml(target[i]) + '</mark>' : escHtml(target[i]);
    }
    return out;
  }

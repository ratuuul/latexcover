  // ---- one-click PDF : lossless PNG of the exact sheet → A4 download ----
  // http(s): html-to-image (SVG serialization, embeds webfonts).
  // file://: html-to-image cannot fetch() local assets (Chrome blocks
  // file:// fetches → CORS), so we rasterize with html2canvas instead —
  // canvas text uses the already-loaded document fonts and the logo loads
  // via <img>, neither of which needs fetch.
  function loadScript(src, test){
    if(test()) return Promise.resolve();
    return new Promise((res, rej)=>{
      const s = document.createElement('script');
      s.src = src;
      s.onload = ()=>res();
      s.onerror = rej;
      document.head.appendChild(s);
    });
  }
  async function rasterizeFile(pr){
    // html2canvas blanks on transformed/clipped content: briefly show the
    // sheet at full size, unscaled and scrolled into view, then restore.
    const prevT = scaler.style.transform, prevW = scaler.style.width, prevH = scaler.style.height;
    const prevX = window.scrollX, prevY = window.scrollY;
    scaler.style.transform = 'none'; scaler.style.width = ''; scaler.style.height = '';
    sheet.scrollIntoView({ block: 'start', inline: 'nearest' });
    await new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r)));
    try{
      const canvas = await window.html2canvas(sheet, { backgroundColor: '#ffffff', scale: pr, logging: false, useCORS: false });
      return canvas.toDataURL('image/png');
    } finally {
      scaler.style.transform = prevT; scaler.style.width = prevW; scaler.style.height = prevH;
      window.scrollTo(prevX, prevY);
      requestAnimationFrame(updateScale);
    }
  }
  async function downloadPDF(){
    flash('Rendering PDF…');
    try{
      // file:// cannot fetch() local assets, which html-to-image requires.
      const fileMode = location.protocol === 'file:';
      if(fileMode){
        await loadScript(
          'https://cdnjs.cloudflare.com/ajax/libs/html2canvas/1.4.1/html2canvas.min.js',
          ()=>!!window.html2canvas
        );
      } else {
        await loadScript(
          'https://cdnjs.cloudflare.com/ajax/libs/html-to-image/1.11.11/html-to-image.min.js',
          ()=>!!window.htmlToImage
        );
      }
      await loadScript(
        'https://cdnjs.cloudflare.com/ajax/libs/jspdf/2.5.1/jspdf.umd.min.js',
        ()=>!!(window.jspdf && window.jspdf.jsPDF)
      );
      // --- wait for the ACTIVE webfonts (all 4 faces) so the snapshot
      // never catches a fallback / faux-bold frame ---
      try{
        if(document.fonts && document.fonts.ready){
          const fam = getComputedStyle(sheet).fontFamily || '';
          const m = fam.match(/'([^']+)'/) || fam.match(/"([^"]+)"/);
          const active = m ? m[1] : 'Palatino Nova';
          await Promise.all([
            document.fonts.load('400 16px "' + active + '"'),
            document.fonts.load('700 16px "' + active + '"'),
            document.fonts.load('italic 400 16px "' + active + '"'),
            document.fonts.load('italic 700 16px "' + active + '"'),
          ]).catch(()=>{});
          await document.fonts.ready;
        }
      }catch(e){/* non-fatal */}
      if(document.activeElement) document.activeElement.blur();
      hideToolbar();
      $$('.combo-list').forEach(l => { l.hidden = true; });
      render();
      await new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r)));
      // HIGH-DPI raster: A4 @96dpi is 794x1123px. PNG is lossless; JPEG chroma
      // subsampling was smudging glyph edges, so never use JPEG.
      const W = sheet.scrollWidth || sheet.offsetWidth;
      const H = sheet.scrollHeight || sheet.offsetHeight;
      const HI_DPI = 5, FALLBACK_DPI = 3;
      let dataUrl = null;
      if(fileMode){
        // ~384 DPI via canvas; retry smaller if the device runs out of memory
        try{
          dataUrl = await rasterizeFile(4);
        }catch(e){
          console.warn('file-mode snapshot failed, retrying smaller', e);
          dataUrl = await rasterizeFile(2);
        }
      } else {
        // ~480 DPI via SVG serialization
        const snapOpts = (pr)=>({
          cacheBust: false, backgroundColor: '#ffffff',
          width: W, height: H,
          canvasWidth: Math.round(W * pr), canvasHeight: Math.round(H * pr),
          pixelRatio: 1, // size already baked into canvasWidth/Height; avoids double-scale blur
          skipAutoScale: true,
          style: { transform: 'none', margin: '0' },
        });
        try{
          dataUrl = await window.htmlToImage.toPng(sheet, snapOpts(HI_DPI));
        }catch(e){
          console.warn('hi-dpi snapshot failed, retrying at standard dpi', e);
          dataUrl = await window.htmlToImage.toPng(sheet, snapOpts(FALLBACK_DPI));
        }
      }
      const JST = window.jspdf.jsPDF;
      const pdf = new JST({ orientation: 'portrait', unit: 'mm', format: 'a4' });
      // 'FAST' = Flate-compress the raster. Without it jsPDF embeds raw RGBA
      // (~89MB at 5x — hangs/fails the download); with it ~0.7MB, still lossless.
      pdf.addImage(dataUrl, 'PNG', 0, 0, 210, 297, undefined, 'FAST');
      const expNo = ((state.expNo || '01') + '').trim() || '01';
      // filename: CourseCode_TeacherName_ExpNo.pdf (filesystem-safe)
      const cleanName = s => String(s ?? '').trim().replace(/[\\/:*?"<>|]/g, '').replace(/\s+/g, ' ').trim();
      const coursePart = cleanName(state.courseCode || defaults.courseCode) || 'Course';
      const teacherPart = cleanName(state.teacher || defaults.teacher) || 'Teacher';
      const expPart = cleanName(expNo) || '01';
      // own attached anchor instead of pdf.save(): the bundled FileSaver
      // dispatches on a detached anchor, which browsers may silently drop.
      const pdfBlob = pdf.output('blob');
      const pdfUrl = URL.createObjectURL(pdfBlob);
      const dl = document.createElement('a');
      dl.href = pdfUrl;
      dl.download = coursePart + '_' + teacherPart + '_' + expPart + '.pdf';
      document.body.appendChild(dl);
      dl.click();
      setTimeout(()=>{ URL.revokeObjectURL(pdfUrl); dl.remove(); }, 4000);
      flash('PDF downloaded');
    }catch(err){
      console.error(err);
      flash('Direct PDF failed — opened print instead');
      doPrint();
    }
  }
